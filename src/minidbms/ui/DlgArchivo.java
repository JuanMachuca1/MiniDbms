    /**
     * @param args the command line arguments
     */
        public static DlgArchivo pedir(java.awt.Frame padre, String titulo, String nombre,
            Politica politica, int minimo, boolean nombreEditable) {
        DlgArchivo d = new DlgArchivo(padre, true);
        d.setTitle(titulo);
        d.txtNombre.setText(nombre);
        d.txtNombre.setEnabled(nombreEditable);
        d.cmbPolitica.setSelectedIndex(politica.ordinal());
        d.spnMinimo.setValue(minimo);
        d.setLocationRelativeTo(padre);
        d.setVisible(true);
        return d.aceptado ? d : null;
    }

    public String nombre() {
        return txtNombre.getText().strip();
    }

    public Politica politica() {
        return Politica.values()[cmbPolitica.getSelectedIndex()];
    }

    public int minimo() {
        return (Integer) spnMinimo.getValue();
    }

    private void aceptar() {
        try {
            spnMinimo.commitEdit();
            if (txtNombre.isEnabled()) {
                Validador.validarNombre(nombre(), "Nombre del archivo");
            }
            aceptado = true;
            dispose();
        } catch (ParseException e) {
            JOptionPane.showMessageDialog(this, "El tamaño mínimo debe ser un número entre 25 y 100000",
                    "Revise los datos", JOptionPane.WARNING_MESSAGE);
        } catch (ErrorBD e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Revise los datos",
                    JOptionPane.WARNING_MESSAGE);
        }
    }
