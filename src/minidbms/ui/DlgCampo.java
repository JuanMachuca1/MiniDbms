        public static void mostrar(java.awt.Frame padre, String titulo,
            Campo inicial, Destino destino) {
        DlgCampo d = new DlgCampo(padre, true);
        d.setTitle(titulo);
        d.destino = destino;
        d.cargar(inicial);
        d.setLocationRelativeTo(padre);
        d.setVisible(true);
    }

    private void cargar(Campo c) {
        id = c == null ? 0 : c.id();
        if (c != null) {
            txtNombre.setText(c.nombre());
            cmbTipo.setSelectedIndex(c.tipo().ordinal());
            txtLongitud.setText(c.longMax() > 0 ? "" + c.longMax() : "");
            chkObligatorio.setSelected(c.obligatorio());
            chkPrimaria.setSelected(c.llavePrimaria());
            txtDefecto.setText(Valores.aTexto(c.valorPorDefecto()));
        }
        actualizar();
    }

    private TipoDato tipoElegido() {
        int i = cmbTipo.getSelectedIndex();
        return i < 0 ? TipoDato.TEXTO : TipoDato.values()[i];
    }

    private void actualizar() {
        txtLongitud.setEnabled(tipoElegido() == TipoDato.TEXTO);
        if (chkPrimaria.isSelected()) {
            chkObligatorio.setSelected(true);
            txtDefecto.setText("");
        }
        chkObligatorio.setEnabled(!chkPrimaria.isSelected());
        txtDefecto.setEnabled(!chkPrimaria.isSelected());
    }

    private Campo leer() throws ErrorBD {
        TipoDato t = tipoElegido();
        int largo = 0;
        if (t == TipoDato.TEXTO) {
            try {
                largo = Integer.parseInt(txtLongitud.getText().strip());
            } catch (NumberFormatException e) {
                throw new ErrorBD("La longitud debe ser un número entero, por ejemplo 40");
            }
        }
        Object valor = Valores.convertir(t, txtDefecto.getText());
        return new Campo(id, txtNombre.getText().strip(), t, largo,
                chkObligatorio.isSelected(), chkPrimaria.isSelected(), valor);
    }

    private void aceptar() {
        try {
            destino.aplicar(leer());
            dispose();
        } catch (ErrorBD e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Revise el campo",
                    JOptionPane.WARNING_MESSAGE);
        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(this, "Error inesperado: " + e, "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }
    
