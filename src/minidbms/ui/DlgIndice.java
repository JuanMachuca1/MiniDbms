        public static DlgIndice pedir(java.awt.Frame padre, String titulo,
            boolean unico, int orden, boolean claseEditable) {
        DlgIndice d = new DlgIndice(padre, true);
        d.setTitle(titulo);
        d.cmbClase.setSelectedIndex(unico ? 0 : 1);
        d.cmbClase.setEnabled(claseEditable);
        d.spnOrden.setValue(orden);
        d.setLocationRelativeTo(padre);
        d.setVisible(true);
        return d.aceptado ? d : null;
    }

    public boolean unico() {
        return cmbClase.getSelectedIndex() == 0;
    }

    public int orden() {
        return (Integer) spnOrden.getValue();
    }

    private void aceptar() {
        try {
            spnOrden.commitEdit();
            aceptado = true;
            dispose();
        } catch (ParseException e) {
            JOptionPane.showMessageDialog(this, "El orden debe ser un número entre 3 y 1000",
                    "Revise los datos", JOptionPane.WARNING_MESSAGE);
        }
    }
